export const calculateSizes = (isSmall, isMobile, isTablet) => {
  return {
    deskScale: isSmall ? 5 : isMobile ? 6 : 6,
    deskPosition: isMobile ? [1.8, -2, 0] : [2.4, -3, 4],
    headPhones: isSmall
      ? [2, -2, 2]
      : isMobile
        ? [3, -4, 3]
        : isTablet
          ? [3, -6, 6.3]
          : [4.5, 0, 10],
    playstationVR: isSmall
      ? [-1, 4, -5]
      : isMobile
        ? [-2, -5, -4]
        : isTablet
          ? [-2, 5, 0]
          : [-8.5, -5, 0],
    potatoHead: isSmall
      ? [5, 7, 0]
      : isMobile
        ? [3, 10, 2]
        : isTablet
          ? [-12, 10, 0]
          : [-10.5, 3.5, 0],
  };
};

